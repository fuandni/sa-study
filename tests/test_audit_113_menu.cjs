'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const d=new JSDOM('<!doctype html><div id="app"></div>',{url:'https://example.test/sa/',runScripts:'outside-only'});
const w=d.window,doc=w.document;
const load=path=>JSON.parse(fs.readFileSync(path,'utf8'));
w.SA_APP_CONFIG=load('data/app_config.json');
w.SA_A1_QUESTIONS=load('a1/data/a1_questions.json');
w.SA_AM2_QUESTIONS=load('am2/data/am2_questions.json');
w.SAValidator={run:()=>({ok:true,question_count:550,a1_count:300,am2_count:250,errors:[]})};
for(const src of ['data/audit_diff_113.js','assets/js/storage.js','assets/js/session_results.js','assets/js/review.js','assets/js/year_analysis.js','assets/js/app.js']){
 w.eval(fs.readFileSync(src,'utf8')+'\n//# sourceURL='+src);
}
const ids=w.SA_AUDIT_DIFF_113.ids,manifest=new Set(ids),all=[...w.SA_A1_QUESTIONS,...w.SA_AM2_QUESTIONS];
const byId=new Map(all.map(q=>[q.id,q]));
const click=selector=>{const el=doc.querySelector(selector);assert.ok(el,'missing '+selector);assert.ok(!el.disabled,'disabled '+selector);el.click()};
const active=()=>w.SAStorage.loadSession();
assert.equal(ids.length,113);
assert.equal(manifest.size,113);
assert.equal(ids.filter(id=>id.startsWith('A1-')).length,49);
assert.equal(ids.filter(id=>id.startsWith('SA-')).length,64);
assert.ok(ids.every(id=>byId.has(id)),'every audit ID must exist in 550-question data');
assert.deepEqual(ids.filter(id=>id.startsWith('A1-2017-')).length,30);
assert.ok(ids.includes('SA-2025-AM2-Q24'),'metadata-only differences must be included');
assert.ok(ids.includes('A1-2023-Q15'),'individual text differences must be included');
assert.ok(!ids.includes('SA-2017-AM2-Q15'),'unchanged question should not be included');
assert.ok(doc.querySelector('#audit113-home'),'home page must offer a dedicated audit menu');
click('#audit113-home');
assert.equal(doc.querySelectorAll('[data-audit113-kind]').length,7);
assert.equal(doc.querySelector('[data-audit113-kind="all"]').disabled,false);
assert.match(doc.querySelector('main').textContent,/図表の表示情報だけが変わった問題も含みます/);
// The entire special collection must be passed through the normal session engine.
click('[data-audit113-kind="all"]');
assert.equal(active().questionIds.length,113);
assert.equal(active().options.scope,'audit-diff-113');
assert.equal(active().options.kind,'all');
assert.equal(new Set(active().questionIds).size,113);
assert.ok(active().questionIds.every(id=>manifest.has(id)));
w.SAApp.home();
assert.ok(doc.querySelector('#resume'),'interrupted 113 question session must be resumable');
click('#resume');
assert.equal(active().questionIds.length,113);
click('#end');
assert.equal(w.SAStorage.loadRecent()[0].total,113);
click('[data-nav="audit113"]');
click('[data-audit113-kind="a1"]');
assert.equal(active().questionIds.length,49);
assert.ok(active().questionIds.every(id=>byId.get(id).section==='午前I'));
click('#end');
click('[data-nav="audit113"]');
click('[data-audit113-kind="am2"]');
assert.equal(active().questionIds.length,64);
assert.ok(active().questionIds.every(id=>byId.get(id).section==='午前II'));
click('#end');
click('[data-nav="audit113"]');
click('[data-audit113-kind="random10"]');
assert.equal(active().questionIds.length,10);
assert.ok(active().questionIds.every(id=>manifest.has(id)));
click('#end');
// A wrong answer becomes available in the ordinary progress and special retry menu.
click('[data-nav="audit113"]');
click('[data-audit113-kind="all"]');
const q=byId.get(active().questionIds[0]);
const wrong=['ア','イ','ウ','エ'].find(k=>k!==q.answer);
click('[data-choice="'+wrong+'"]');
click('#flag');
assert.equal(active().answeredCount,1);
click('#end');
assert.equal(w.SAStorage.aggregate(w.SAStorage.load(),q.id).wrong,1);
click('[data-nav="audit113"]');
assert.match(doc.querySelector('main').textContent,/誤答経験あり 1問/);
assert.match(doc.querySelector('main').textContent,/★ 要復習 1問/);
click('[data-audit113-kind="wrong"]');
assert.deepEqual(Array.from(active().questionIds),[q.id]);
click('#end');
click('[data-nav="audit113"]');
click('[data-audit113-kind="unanswered"]');
assert.equal(active().questionIds.length,112);
assert.ok(!active().questionIds.includes(q.id));
click('#end');
click('[data-nav="audit113"]');
click('[data-audit113-kind="flagged"]');
assert.deepEqual(Array.from(active().questionIds),[q.id]);
click('#end');
click('[data-nav="audit113"]');
// Reject stale/incomplete manifest rather than silently offering fewer than 113.
w.SA_AUDIT_DIFF_113.ids.pop();
w.SAApp.audit113();
assert.equal(doc.querySelector('[data-audit113-kind="all"]').disabled,true);
assert.match(doc.querySelector('main').textContent,/ID構成が一致しません/);
console.log('PASS: exact 113 IDs, home and nav entry, full/49/64/random/unanswered/wrong/flagged subsets, resume, history and missing-ID safety');
